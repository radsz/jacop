#!/usr/bin/env python3
"""Generate self-contained MiniZinc benchmarks for extensional constraints.

Families follow the classic table-propagator benchmark sets (Compact-Table, CT*, CT-neg, MDD4R papers):
random positive tables (randtab), negative tables posted as `not table` (randneg), short tables with
wildcards expanded (shorttab), Boolean tables (booltab), functional tables z = f(x, y) (functab),
Dubois parity (dubois), crosswords (crossword), kakuro (kakuro), TSP with a distance table (tsp) and
random MDDs (mdd). Every instance is deterministic in (family, parameters, seed), and every model uses a
fixed input-order search, so its first solution does not depend on propagation strength.

The instances in jacop-benchmarks/src/test/fz/*/table_*, mdd_random were made with the parameters in
extensional-benchmarks-grid.txt (one "family name key=value ..." line per instance), compiled with
`minizinc -c --solver org.jacop` (MiniZinc 2.10.0) and cross-checked against Gecode and Chuffed.

The crossword family needs the public-domain word list words_alpha.txt from
https://github.com/dwyl/english-words; point the WORDS environment variable at it.

usage: extensional-benchmarks.py <outdir> <family> <name> key=value ...
"""
import itertools
import os
import random
import sys

WORDS = os.environ.get("WORDS", "words_alpha.txt")


def mat(rows):
    return "[|" + "|".join(",".join(map(str, r)) for r in rows) + "|]"


def header(family, params, seed, text):
    p = " ".join(f"{k}={v}" for k, v in params.items())
    return (f"% Extensional constraint benchmark, family {family} ({p}, seed {seed}).\n"
            f"% {text}\n% Generated by a deterministic Python generator; the search is fixed so that the\n"
            f"% first solution does not depend on propagation strength.\n\n")


def rand_tables(r, n, d, m, arity, t, planted):
    """m tables of arity `arity` over n variables, t distinct tuples each (planted solution included)."""
    sol = [r.randrange(d) for _ in range(n)]
    cons = []
    seen = set()
    while len(cons) < m:
        sc = tuple(sorted(r.sample(range(n), arity)))
        if sc in seen:
            continue
        seen.add(sc)
        tup = set()
        if planted:
            tup.add(tuple(sol[v] for v in sc))
        while len(tup) < t:
            tup.add(tuple(r.randrange(d) for _ in range(arity)))
        cons.append((sc, sorted(tup)))
    return cons


def gen_randtab(r, P, neg=False):
    n, d, m, a, t = P["n"], P["d"], P["m"], P["a"], P["t"]
    planted = P.get("planted", 1) and not neg
    cons = rand_tables(r, n, d, m, a, t, planted)
    kind = "negative (conflict) tables posted as `not table`" if neg else "positive tables"
    s = header("randneg" if neg else "randtab", P, P["seed"],
               f"{m} random {kind} of arity {a} with {t} tuples each over {n} variables with domain 0..{d - 1}.")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{n}] of var 0..{d - 1}: x;\n\n"
    for i, (sc, tup) in enumerate(cons):
        s += f"array[1..{len(tup)}, 1..{a}] of int: t{i + 1} = {mat(tup)};\n"
    s += "\n"
    for i, (sc, tup) in enumerate(cons):
        args = ", ".join(f"x[{v + 1}]" for v in sc)
        s += f"constraint {'not ' if neg else ''}table([{args}], t{i + 1});\n"
    s += "\nsolve :: int_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


def gen_dubois(r, P):
    """2n ternary parity constraints, every variable in exactly two of them, odd total parity: UNSAT."""
    n = P["n"]
    nv = 3 * n
    while True:
        seq = list(range(nv)) + r.sample(range(nv), nv)
        triples = [seq[i:i + 3] for i in range(0, len(seq), 3)]
        if all(len(set(tr)) == 3 for tr in triples):
            break
    rhs = [0] * len(triples)
    rhs[r.randrange(len(triples))] = 1
    s = header("dubois", P, P["seed"],
               f"Dubois-style parity: {2 * n} ternary xor tables over {nv} 0/1 variables, each variable in two tables, "
               "odd total parity, hence unsatisfiable.")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{nv}] of var 0..1: x;\n"
    for p in (0, 1):
        tup = [t for t in itertools.product((0, 1), repeat=3) if sum(t) % 2 == p]
        s += f"array[1..4, 1..3] of int: parity{p} = {mat(tup)};\n"
    s += "\n"
    for tr, p in zip(triples, rhs):
        s += f"constraint table([{', '.join(f'x[{v + 1}]' for v in tr)}], parity{p});\n"
    s += "\nsolve :: int_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


def slots(black):
    h, w = len(black), len(black[0])
    out = []
    for i in range(h):
        j = 0
        while j < w:
            if black[i][j]:
                j += 1
                continue
            k = j
            while k < w and not black[i][k]:
                k += 1
            if k - j >= 2:
                out.append([(i, c) for c in range(j, k)])
            j = k
    for j in range(w):
        i = 0
        while i < h:
            if black[i][j]:
                i += 1
                continue
            k = i
            while k < h and not black[k][j]:
                k += 1
            if k - i >= 2:
                out.append([(c, j) for c in range(i, k)])
            i = k
    return out


def gen_crossword(r, P):
    h, w, nb, per = P["h"], P["w"], P["black"], P["words"]
    black = [[0] * w for _ in range(h)]
    cells = [(i, j) for i in range(h) for j in range(w)]
    for (i, j) in r.sample(cells, nb):
        black[i][j] = 1
        black[h - 1 - i][w - 1 - j] = 1
    sl = slots(black)
    lens = sorted({len(s) for s in sl})
    words = {}
    for line in open(WORDS):
        wd = line.strip().lower()
        if wd.isalpha() and wd.isascii() and len(wd) in lens:
            words.setdefault(len(wd), []).append(wd)
    s = header("crossword", P, P["seed"],
               f"Fill a {h}x{w} grid ({sum(map(sum, black))} black cells) with words: one table per slot, letters 0..25. "
               "Words: a seeded sample of the public-domain dwyl/english-words list.")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{h}, 1..{w}] of var 0..25: x;\n"
    for i in range(h):
        for j in range(w):
            if black[i][j]:
                s += f"constraint x[{i + 1},{j + 1}] = 0;\n"
    for L in lens:
        ws = sorted(r.sample(sorted(set(words[L])), min(per, len(set(words[L])))))
        s += f"array[1..{len(ws)}, 1..{L}] of int: words{L} = {mat([[ord(c) - 97 for c in wd] for wd in ws])};\n"
    s += "\n"
    for slot in sl:
        s += f"constraint table([{', '.join(f'x[{i + 1},{j + 1}]' for i, j in slot)}], words{len(slot)});\n"
    s += ("\nsolve :: int_search([x[i,j] | i in 1..%d, j in 1..%d], input_order, indomain_min) satisfy;\n\n" % (h, w))
    s += "output [if fix(x[i,j]) = 0 /\\ false then \"\" else \"\" endif ++ show(x[i,j]) ++ if j = %d then \"\\n\" else \" \" endif | i in 1..%d, j in 1..%d];\n" % (w, h, w)
    return s


def gen_kakuro(r, P):
    """Random kakuro: random white/black layout, filled with distinct digits per run, sums as clues."""
    h, w = P["h"], P["w"]
    while True:
        black = [[1 if i == 0 or j == 0 or r.random() < P["p"] else 0 for j in range(w)] for i in range(h)]
        sl = slots(black)
        covered = {c for s in sl for c in s}
        white = {(i, j) for i in range(h) for j in range(w) if not black[i][j]}
        if covered != white or any(len(s) > P.get("maxrun", 9) for s in sl):
            continue
        # fill digits greedily with backtracking-free retries
        ok = False
        for _ in range(200):
            val = {}
            good = True
            for c in sorted(white):
                used = {val[x] for s in sl if c in s for x in s if x in val}
                cand = [d for d in range(1, 10) if d not in used]
                if not cand:
                    good = False
                    break
                val[c] = r.choice(cand)
            if good:
                ok = True
                break
        if ok:
            break
    combos = {}
    for s in sl:
        L, tot = len(s), sum(val[c] for c in s)
        combos[(L, tot)] = [p for p in itertools.permutations(range(1, 10), L) if sum(p) == tot]
    s = header("kakuro", P, P["seed"],
               f"Random {h}x{w} kakuro; every run is one table holding all distinct-digit tuples with the clue sum.")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{h}, 1..{w}] of var 0..9: x;\n"
    for i in range(h):
        for j in range(w):
            if black[i][j]:
                s += f"constraint x[{i + 1},{j + 1}] = 0;\n"
    for (L, tot), tup in sorted(combos.items()):
        s += f"array[1..{len(tup)}, 1..{L}] of int: k{L}_{tot} = {mat(tup)};\n"
    s += "\n"
    for slot in sl:
        L, tot = len(slot), sum(val[c] for c in slot)
        s += f"constraint table([{', '.join(f'x[{i + 1},{j + 1}]' for i, j in slot)}], k{L}_{tot});\n"
    s += ("\nsolve :: int_search([x[i,j] | i in 1..%d, j in 1..%d], input_order, indomain_min) satisfy;\n\n" % (h, w))
    s += "output [show(x[i,j]) ++ if j = %d then \"\\n\" else \" \" endif | i in 1..%d, j in 1..%d];\n" % (w, h, w)
    return s


def gen_tsp(r, P):
    n = P["n"]
    pts = [(r.randrange(100), r.randrange(100)) for _ in range(n)]
    dist = [[0 if i == j else round(((pts[i][0] - pts[j][0]) ** 2 + (pts[i][1] - pts[j][1]) ** 2) ** 0.5) for j in range(n)]
            for i in range(n)]
    tup = [(i + 1, j + 1, dist[i][j]) for i in range(n) for j in range(n) if i != j]
    s = header("tsp", P, P["seed"],
               f"TSP on {n} random points: tour order x with alldifferent, each leg length from a (from, to, length) table.")
    s += "include \"table.mzn\";\ninclude \"alldifferent.mzn\";\n\n"
    s += f"int: n = {n};\narray[1..n] of var 1..n: x;\narray[1..n] of var 0..150: d;\n"
    s += f"array[1..{len(tup)}, 1..3] of int: dist = {mat(tup)};\n\n"
    s += "constraint x[1] = 1;\nconstraint alldifferent(x);\nconstraint x[2] < x[n];\n"
    s += "constraint forall(i in 1..n)(table([x[i], x[i mod n + 1], d[i]], dist));\n\n"
    s += "solve :: seq_search([int_search(x, input_order, indomain_min), int_search(d, input_order, indomain_min)]) minimize sum(d);\n\n"
    s += "output [\"x = \\(x);\\nlength = \\(sum(d));\\n\"];\n"
    return s


def rand_mdd(r, arity, d, width, keep):
    """Layered MDD: `width` nodes per inner layer; each node keeps a value with prob `keep`."""
    layers = [[1]]
    nid = 2
    for _ in range(1, arity):
        layers.append(list(range(nid, nid + width)))
        nid += width
    edges = []
    for li in range(arity):
        for node in layers[li]:
            for v in range(d):
                if r.random() < keep:
                    to = 0 if li == arity - 1 else r.choice(layers[li + 1])
                    edges.append((node, v, to))
    # reduce: drop nodes without outgoing edges iteratively, MiniZinc's mdd accepts dangling nodes anyway
    level = [li + 1 for li in range(arity) for _ in layers[li]]
    return nid - 1, level, edges


def gen_mdd(r, P):
    n, d, m, a, wd, keep = P["n"], P["d"], P["m"], P["a"], P["width"], P["keep"]
    s = header("mdd", P, P["seed"],
               f"{m} random MDD constraints of arity {a} (width {wd}) over {n} variables with domain 0..{d - 1}.")
    s += "include \"mdd.mzn\";\n\n"
    s += f"array[1..{n}] of var 0..{d - 1}: x;\n\n"
    for c in range(m):
        sc = r.sample(range(n), a)
        N, level, edges = rand_mdd(r, a, d, wd, keep)
        s += (f"constraint mdd([{', '.join(f'x[{v + 1}]' for v in sc)}], {N}, {level}, {len(edges)}, "
              f"{[e[0] for e in edges]}, [{', '.join('{%d}' % e[1] for e in edges)}], {[e[2] for e in edges]});\n")
    s += "\nsolve :: int_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


def gen_shorttab(r, P):
    """Short tables (tuples with wildcards) expanded to plain tuples, as MiniZinc has no `*`."""
    n, d, m, a, t, star = P["n"], P["d"], P["m"], P["a"], P["t"], P["star"]
    sol = [r.randrange(d) for _ in range(n)]
    s = header("shorttab", P, P["seed"],
               f"{m} tables of arity {a} over {n} variables (domain 0..{d - 1}), each the expansion of {t} short tuples "
               f"with a wildcard probability of {star}; a planted solution is included. Target for CT* compression.")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{n}] of var 0..{d - 1}: x;\n\n"
    cons = []
    for c in range(m):
        sc = r.sample(range(n), a)
        short = [tuple(sol[v] if r.random() < star else sol[v] for v in sc)]
        while len(short) < t:
            short.append(tuple(-1 if r.random() < star else r.randrange(d) for _ in range(a)))
        full = set()
        for st in short:
            full.update(itertools.product(*[range(d) if v == -1 else (v,) for v in st]))
        cons.append((sc, sorted(full)))
    for i, (sc, tup) in enumerate(cons):
        s += f"array[1..{len(tup)}, 1..{a}] of int: t{i + 1} = {mat(tup)};\n"
    s += "\n"
    for i, (sc, tup) in enumerate(cons):
        s += f"constraint table([{', '.join(f'x[{v + 1}]' for v in sc)}], t{i + 1});\n"
    s += "\nsolve :: int_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


def gen_functab(r, P):
    """Functional ternary tables z = f(x, y) with random f, chained into a network; one table per triple."""
    n, d, m = P["n"], P["d"], P["m"]
    s = header("functab", P, P["seed"],
               f"{m} functional tables z = f(x, y) (random f, d*d tuples each) over {n} variables with domain 0..{d - 1}, "
               "plus an alldifferent; tables of this shape are typical of element-like or arithmetic encodings.")
    s += "include \"table.mzn\";\ninclude \"alldifferent.mzn\";\n\n"
    s += f"array[1..{n}] of var 0..{d - 1}: x;\n\n"
    for c in range(m):
        tup = [(i, j, r.randrange(d)) for i in range(d) for j in range(d)]
        s += f"array[1..{len(tup)}, 1..3] of int: f{c + 1} = {mat(tup)};\n"
    s += "\n"
    for c in range(m):
        a, b, z = r.sample(range(n), 3)
        s += f"constraint table([x[{a + 1}], x[{b + 1}], x[{z + 1}]], f{c + 1});\n"
    s += f"constraint alldifferent([x[i] | i in 1..{min(n, d)}]);\n"
    s += "\nsolve :: int_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


def gen_booltab(r, P):
    """Boolean tables (table_bool) of arity a with t random tuples plus a planted solution."""
    n, m, a, t = P["n"], P["m"], P["a"], P["t"]
    sol = [r.random() < 0.5 for _ in range(n)]
    s = header("booltab", P, P["seed"],
               f"{m} Boolean tables of arity {a} with {t} tuples each over {n} Boolean variables (table_bool).")
    s += "include \"table.mzn\";\n\n"
    s += f"array[1..{n}] of var bool: x;\n\n"
    b = lambda v: "true" if v else "false"
    for c in range(m):
        sc = r.sample(range(n), a)
        tup = {tuple(sol[v] for v in sc)}
        while len(tup) < t:
            tup.add(tuple(r.random() < 0.5 for _ in range(a)))
        rows = sorted(tup)
        s += f"array[1..{len(rows)}, 1..{a}] of bool: t{c + 1} = {mat([[b(v) for v in row] for row in rows])};\n"
        s += f"constraint table([{', '.join(f'x[{v + 1}]' for v in sc)}], t{c + 1});\n"
    s += "\nsolve :: bool_search(x, input_order, indomain_min) satisfy;\n\noutput [\"x = \\(x);\\n\"];\n"
    return s


GEN = {
    "randtab": gen_randtab,
    "randneg": lambda r, P: gen_randtab(r, P, neg=True),
    "dubois": gen_dubois,
    "crossword": gen_crossword,
    "kakuro": gen_kakuro,
    "tsp": gen_tsp,
    "mdd": gen_mdd,
    "shorttab": gen_shorttab,
    "functab": gen_functab,
    "booltab": gen_booltab,
}

if __name__ == "__main__":
    outdir, fam, name = sys.argv[1:4]
    P = {}
    for kv in sys.argv[4:]:
        k, v = kv.split("=")
        P[k] = float(v) if "." in v else int(v)
    P.setdefault("seed", 1)
    r = random.Random(f"{fam}-{P['seed']}")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, name + ".mzn"), "w") as f:
        f.write(GEN[fam](r, P))
