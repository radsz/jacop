package org.jacop.fz.xcsp;

/** An XCSP3 instance the reader cannot read: bad syntax or a construct it does not support. */
public class XcspException extends RuntimeException {

  private static final long serialVersionUID = 1L;

  /**
   * Creates the exception.
   *
   * @param message what the reader could not read
   */
  public XcspException(String message) {
    super(message);
  }
}
